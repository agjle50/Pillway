"""Builds docs/french_review.md: every French string in the app, for a French speaker to approve.

Run:  python tools/generate_french_review.py
Reads the data files (never the code), so it always matches what the app shows.
When a line is approved, fix it in the data file it names; when all are done, set
"reviewed": true in data/french_strings.json (the app then shows "Traduction révisée").
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name):
    return json.loads((ROOT / "data" / name).read_text(encoding="utf-8"))


def rows_from(node, path=""):
    """Yield (path, english, french) for every {"en": ..., "fr": ...} pair in a JSON tree."""
    if isinstance(node, dict):
        if "en" in node and "fr" in node and isinstance(node["fr"], str):
            yield path, node["en"], node["fr"], node.get("fr_source", "needs_review")
        for key, value in node.items():
            if key.endswith("_en") and key[:-3] + "_fr" in node and isinstance(value, str):
                yield f"{path}.{key[:-3]}", value, node[key[:-3] + "_fr"], "needs_review"
            if isinstance(value, (dict, list)):
                yield from rows_from(value, f"{path}.{key}" if path else key)
    elif isinstance(node, list):
        for index, item in enumerate(node):
            label = item.get("id", index) if isinstance(item, dict) else index
            yield from rows_from(item, f"{path}[{label}]")


def main():
    lines = ["# French review list (Canadian French)", "",
             "Generated by `python tools/generate_french_review.py`. Everything here was written by the AI or by a",
             "machine and **needs review** unless marked *Pillway PDF* (wording copied from Pillway's own care plan).",
             "Tick a box when the line is approved, and fix the wording in the file named in the heading.", ""]
    total = 0
    for name in ("french_strings.json", "questions.json", "advice.json", "care_plan_template.json", "check_in_messages.json"):
        rows = list(rows_from(load(name)))
        lines += [f"## data/{name}  ({len(rows)} strings)", "", "| ✓ | Where | English | Français | Source |", "|---|---|---|---|---|"]
        for where, english, french, source in rows:
            clean = lambda text: str(text).replace("|", "\\|").replace("\n", " ")
            label = "Pillway PDF" if source == "pillway_pdf" else "needs review"
            lines.append(f"| ☐ | `{where}` | {clean(english)} | {clean(french)} | {label} |")
        lines.append("")
        total += len(rows)
    lines.insert(5, f"**{total} strings in total.**\n")
    out = ROOT / "docs" / "french_review.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({total} strings)")


if __name__ == "__main__":
    main()
